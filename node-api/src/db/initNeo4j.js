// ─── Инициализация ────────────────────────────────────────────────────────────
async function initNeo4j() {
  const session = driver.session();
  try {

    // 1. Эмоции
    for (const e of EMOTIONS) {
      await session.run(
        `MERGE (em:Emotion {name: $name})
         SET em.color = $color, em.animation = $animation, em.empathy = $empathy,
             em.placeholder = $placeholder, em.recommendation = $recommendation
         REMOVE em.uiStyle, em.accentColor`,
        e
      );
    }

    // 2. Противоположные эмоции
    for (const [a, b] of OPPOSITES) {
      await session.run(
        `MATCH (a:Emotion {name: $a}), (b:Emotion {name: $b})
         MERGE (a)-[:OPPOSITE]->(b)
         MERGE (b)-[:OPPOSITE]->(a)`,
        { a, b }
      );
    }

    // 3. Теги
    const allTags = LIFE_AREAS.flatMap(area => area.tags);
    for (const tag of allTags) {
      await session.run('MERGE (t:Tag {name: $name})', { name: tag });
    }

    // 4. Сферы жизни + связи с тегами
    for (const area of LIFE_AREAS) {
      await session.run(
        'MERGE (a:LifeArea {name: $name}) SET a.icon = $icon',
        { name: area.name, icon: area.icon }
      );
      for (const tag of area.tags) {
        await session.run(
          `MATCH (t:Tag {name: $tag}), (a:LifeArea {name: $area})
           MERGE (t)-[:BELONGS_TO]->(a)`,
          { tag, area: area.name }
        );
      }
    }

    // 5. Типы стратегий
    for (const st of STRATEGY_TYPES) {
      await session.run(
        `MERGE (s:StrategyType {name: $name})
         SET s.icon = $icon, s.description = $description`,
        st
      );
    }

    // 6. Стратегии + связь с типом
    for (const s of STRATEGIES) {
      await session.run(
        `MERGE (st:Strategy {name: $name})
         SET st.duration = $duration, st.icon = $icon, st.description = $description`,
        { name: s.name, duration: s.duration, icon: s.icon, description: s.description }
      );
      await session.run(
        `MATCH (st:Strategy {name: $strategy}), (t:StrategyType {name: $type})
         MERGE (st)-[:TYPE]->(t)`,
        { strategy: s.name, type: s.type }
      );
    }

    // 7. Эмоция → стратегии (SUGGESTS)
    for (const [emotion, strategies] of EMOTION_STRATEGIES) {
      for (const strategy of strategies) {
        await session.run(
          `MATCH (em:Emotion {name: $emotion}), (st:Strategy {name: $strategy})
           MERGE (em)-[:SUGGESTS]->(st)`,
          { emotion, strategy }
        );
      }
    }

    // 8. Стратегия → теги (HELPS_WITH)
    // Именно пересечение SUGGESTS + HELPS_WITH определяет "рекомендуемую" стратегию
    for (const [strategy, tags] of STRATEGY_TAGS) {
      for (const tag of tags) {
        await session.run(
          `MATCH (st:Strategy {name: $strategy}), (t:Tag {name: $tag})
           MERGE (st)-[:HELPS_WITH]->(t)`,
          { strategy, tag }
        );
      }
    }

    // 9. Правила тег + эмоция → текст (остаётся для фразы маскота)
    for (const [tag, emotion, recommendation] of RULES) {
      await session.run(
        `MATCH (t:Tag {name: $tag}), (em:Emotion {name: $emotion})
         MERGE (t)-[r:RULE]->(em)
         SET r.recommendation = $recommendation`,
        { tag, emotion, recommendation }
      );
    }

    console.log('Neo4j knowledge graph initialized successfully');

  } catch (err) {
    console.error('Neo4j init error:', err.message);
  } finally {
    await session.close();
  }
}

module.exports = initNeo4j;